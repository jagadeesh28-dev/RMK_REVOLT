class ChemistryConditionalNormalizer:
    """
    Normalizes feature values conditioned on identified chemistry.
    STRICT NON-LEAKAGE: Parameters (mean, std, plateau) are estimated
    ONLY on training batteries.
    """
    def __init__(self, target_features: Optional[List[str]] = None):
        self.target_features = target_features or ["V_MEAN", "DELTA_V_TOTAL", "DELTA_V_OHMIC", "R0_OHMIC"]
        self.stats_: Dict[str, Dict[str, Tuple[float, float]]] = {}
        self.global_stats_: Dict[str, Tuple[float, float]] = {}
        self.is_fitted = False

    def fit(self, X: np.ndarray, chemistries: List[str], feature_names: List[str]) -> "ChemistryConditionalNormalizer":
        """
        Fits mean and scale per chemistry using training data only.
        """
        self.stats_ = {}
        self.global_stats_ = {}
        chem_array = np.asarray(chemistries)

        for j, fname in enumerate(feature_names):
            if fname not in self.target_features:
                continue
            vals = X[:, j]
            glob_mean = float(np.mean(vals))
            glob_std = float(np.std(vals))
            if glob_std < 1e-8:
                glob_std = 1.0
            self.global_stats_[fname] = (glob_mean, glob_std)

            self.stats_[fname] = {}
            for chem in np.unique(chem_array):
                mask = (chem_array == chem)
                chem_vals = vals[mask]
                if len(chem_vals) > 0:
                    c_mean = float(np.mean(chem_vals))
                    c_std = float(np.std(chem_vals))
                    if c_std < 1e-8:
                        c_std = glob_std
                    self.stats_[fname][chem] = (c_mean, c_std)

        self.is_fitted = True
        return self

    def transform(self, X: np.ndarray, chemistries: List[str], feature_names: List[str]) -> np.ndarray:
        """
        Transforms features by subtracting chemistry-specific mean and dividing by scale.
        For UNKNOWN or unseen chemistries, falls back to global training statistics.
        """
        if not self.is_fitted:
            raise RuntimeError("Normalizer must be fitted before transform.")
        X_out = np.copy(X)
        chem_array = np.asarray(chemistries)

        for j, fname in enumerate(feature_names):
            if fname not in self.target_features or fname not in self.stats_:
                continue
            glob_mean, glob_std = self.global_stats_[fname]
            for i in range(len(X)):
                chem = chem_array[i]
                if chem in self.stats_[fname]:
                    c_mean, c_std = self.stats_[fname][chem]
                    X_out[i, j] = (X[i, j] - c_mean) / c_std
                else:
                    # Fallback to global statistics for UNKNOWN / shifted chemistry
                    X_out[i, j] = (X[i, j] - glob_mean) / glob_std
        return X_out


class R0ContextNormalizer:
    """
    Investigates and implements context normalization for R0:
    R0_norm = f(R0, SOC, temperature, current, duration, chemistry)

    Modes:
        1. RAW: R0
        2. SOC_CONDITIONED: R0 / f_soc(SOC)
        3. TEMP_CONDITIONED: R0 / Arrhenius(T)
        4. SOC_TEMP_CONDITIONED: R0 / (f_soc * Arrhenius)
        5. CHEMISTRY_CONDITIONED: R0 / R0_nominal(chem)
        6. FULLY_CONTEXTUALIZED: R0 / (f_soc * Arrhenius * R0_nominal * (I/10.0)^alpha)
    """
    def __init__(self, mode: str = "RAW", ref_temp_c: float = 25.0, ea_ev: float = 0.35):
        self.mode = mode
        self.ref_temp_k = ref_temp_c + 273.15
        self.ea_ev = ea_ev
        self.k_b = 8.617333262145e-5 # eV / K

    def normalize(
        self,
        r0: float,
        soc: float,
        temperature_c: float,
        current_a: float = 10.0,
        chemistry: str = "LFP"
    ) -> float:
        if self.mode == "RAW":
            return r0

        t_k = temperature_c + 273.15
        # Arrhenius factor for temperature: R0(T) ~ exp(Ea / (kB * T))
        # Relative to 25C reference: f_temp = exp(Ea/kB * (1/T - 1/T_ref))
        f_temp = math.exp((self.ea_ev / self.k_b) * (1.0 / t_k - 1.0 / self.ref_temp_k))

        # SOC impedance curve factor (typical U-shape: high at low SOC and high SOC)
        # Centered at mid-SOC 0.50
        f_soc = 1.0 + 0.35 * (soc - 0.55)**2

        # Chemistry nominal base resistance
        chem_base = 2.0 if chemistry == "LFP" else (1.6 if chemistry == "NMC" else 5.0)

        if self.mode == "SOC_CONDITIONED":
            return r0 / f_soc
        elif self.mode == "TEMP_CONDITIONED":
            return r0 / f_temp
        elif self.mode == "SOC_TEMP_CONDITIONED":
            return r0 / (f_soc * f_temp)
        elif self.mode == "CHEMISTRY_CONDITIONED":
            return r0 / chem_base
        elif self.mode == "FULLY_CONTEXTUALIZED":
            # Include slight current nonlinearity if amplitude deviates from 10A
            i_factor = (current_a / 10.0)**(-0.05) if current_a > 0 else 1.0
            return r0 / (f_soc * f_temp * chem_base * i_factor)
        else:
            return r0


