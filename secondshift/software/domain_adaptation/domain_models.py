class CrossDomainRidgeModel:
    """
    Regularized Ridge Regression baseline with battery-disjoint & chemistry awareness.
    Supports:
        - Naive (pooled across chemistries)
        - Chemistry-Stratified (separate sub-models per chemistry)
        - Chemistry-Conditioned Normalization
        - Epistemic uncertainty estimation via residual variance and distance
    """
    def __init__(self, alpha: float = 1.0, fit_intercept: bool = True):
        self.alpha = alpha
        self.fit_intercept = fit_intercept
        self.weights: Optional[np.ndarray] = None
        self.intercept: float = 0.0
        self.sub_models: Dict[str, "CrossDomainRidgeModel"] = {}
        self.training_feature_mean: Optional[np.ndarray] = None
        self.training_feature_std: Optional[np.ndarray] = None
        self.residual_variance: float = 0.01
        self.is_fitted = False

    def fit(self, X: np.ndarray, y: np.ndarray) -> "CrossDomainRidgeModel":
        X = np.asarray(X, dtype=float)
        y = np.asarray(y, dtype=float)
        if X.ndim == 1:
            X = X.reshape(-1, 1)

        n_samples, n_features = X.shape
        self.training_feature_mean = np.mean(X, axis=0)
        self.training_feature_std = np.std(X, axis=0)
        self.training_feature_std[self.training_feature_std < 1e-8] = 1.0

        if self.fit_intercept:
            X_mean = np.mean(X, axis=0)
            y_mean = np.mean(y)
            X_c = X - X_mean
            y_c = y - y_mean
        else:
            X_mean = np.zeros(n_features)
            y_mean = 0.0
            X_c = X
            y_c = y

        reg = self.alpha * np.eye(n_features)
        A = X_c.T @ X_c + reg
        try:
            self.weights = np.linalg.solve(A, X_c.T @ y_c)
        except np.linalg.LinAlgError:
            self.weights = np.linalg.pinv(A) @ (X_c.T @ y_c)

        if self.fit_intercept:
            self.intercept = float(y_mean - X_mean @ self.weights)
        else:
            self.intercept = 0.0

        preds = X @ self.weights + self.intercept
        residuals = y - preds
        self.residual_variance = float(np.var(residuals)) if len(residuals) > 1 else 0.01
        self.is_fitted = True
        return self

    def predict(self, X: np.ndarray) -> np.ndarray:
        if not self.is_fitted:
            raise RuntimeError("Model must be fitted before predict.")
        X = np.asarray(X, dtype=float)
        if X.ndim == 1:
            X = X.reshape(-1, 1)
        return X @ self.weights + self.intercept

    def predict_with_uncertainty(
        self,
        X: np.ndarray,
        chemistry_in_train: bool = True
    ) -> Tuple[np.ndarray, np.ndarray]:
        """
        Predicts SOH and computes epistemic uncertainty (sigma).
        If chemistry or feature distribution is outside training domain,
        epistemic uncertainty is inflated.
        """
        preds = self.predict(X)
        X = np.asarray(X, dtype=float)
        if X.ndim == 1:
            X = X.reshape(-1, 1)

        # Base aleatoric sigma from training residual variance
        base_sigma = math.sqrt(max(1e-6, self.residual_variance))
        sigmas = []

        for i in range(len(X)):
            # Distance from training distribution center
            z = (X[i] - self.training_feature_mean) / self.training_feature_std
            dist = float(np.linalg.norm(z)) / math.sqrt(len(z))

            # Epistemic inflation
            inflation = 1.0 + 0.5 * dist
            if not chemistry_in_train:
                # Out-of-domain chemistry penalty
                inflation *= 2.5

            sigmas.append(base_sigma * inflation)

        return preds, np.asarray(sigmas)


class StratifiedChemistryModel:
    """
    Maintains distinct Ridge models per known chemistry (Model B).
    Routes specimens to their chemistry-specific model.
    Falls back to a global model with flagged uncertainty for UNKNOWN chemistries.
    """
    def __init__(self, alpha: float = 1.0):
        self.alpha = alpha
        self.models: Dict[str, CrossDomainRidgeModel] = {}
        self.global_model = CrossDomainRidgeModel(alpha=alpha)
        self.is_fitted = False

    def fit(self, X: np.ndarray, y: np.ndarray, chemistries: List[str]) -> "StratifiedChemistryModel":
        chem_array = np.asarray(chemistries)
        self.global_model.fit(X, y)
        self.models = {}

        for chem in np.unique(chem_array):
            mask = (chem_array == chem)
            if np.sum(mask) >= 2:
                sub_model = CrossDomainRidgeModel(alpha=self.alpha)
                sub_model.fit(X[mask], y[mask])
                self.models[chem] = sub_model

        self.is_fitted = True
        return self

    def predict(self, X: np.ndarray, chemistries: List[str]) -> np.ndarray:
        if not self.is_fitted:
            raise RuntimeError("Model must be fitted before predict.")
        preds = np.zeros(len(X))
        for i, chem in enumerate(chemistries):
            if chem in self.models:
                preds[i] = self.models[chem].predict(X[i:i+1])[0]
            else:
                preds[i] = self.global_model.predict(X[i:i+1])[0]
        return preds


class HierarchicalSharedModel:
    """
    Hierarchical / Shared shrinkage model (Model D).
    Combines a global shared prior with chemistry-specific deviations
    using regularized shrinkage:
        w_chem = (A_chem + lambda * I)^-1 (X_c^T y_c + lambda * w_global)
    """
    def __init__(self, alpha_global: float = 1.0, alpha_shrink: float = 5.0):
        self.alpha_global = alpha_global
        self.alpha_shrink = alpha_shrink
        self.global_weights: Optional[np.ndarray] = None
        self.global_intercept: float = 0.0
        self.chem_weights: Dict[str, np.ndarray] = {}
        self.chem_intercepts: Dict[str, float] = {}
        self.is_fitted = False

    def fit(self, X: np.ndarray, y: np.ndarray, chemistries: List[str]) -> "HierarchicalSharedModel":
        X = np.asarray(X, dtype=float)
        y = np.asarray(y, dtype=float)
        chem_array = np.asarray(chemistries)
        n_samples, n_features = X.shape

        # Step 1: Fit global model
        global_ridge = CrossDomainRidgeModel(alpha=self.alpha_global)
        global_ridge.fit(X, y)
        self.global_weights = global_ridge.weights
        self.global_intercept = global_ridge.intercept

        # Step 2: Fit chemistry-specific shrinkage models
        self.chem_weights = {}
        self.chem_intercepts = {}
        for chem in np.unique(chem_array):
            mask = (chem_array == chem)
            X_c = X[mask]
            y_c = y[mask]
            if len(X_c) < 2:
                self.chem_weights[chem] = np.copy(self.global_weights)
                self.chem_intercepts[chem] = self.global_intercept
                continue

            X_mean = np.mean(X_c, axis=0)
            y_mean = np.mean(y_c)
            Xc_centered = X_c - X_mean
            yc_centered = y_c - y_mean

            # Shrink toward global weights
            reg = self.alpha_shrink * np.eye(n_features)
            A = Xc_centered.T @ Xc_centered + reg
            rhs = Xc_centered.T @ yc_centered + self.alpha_shrink * self.global_weights
            try:
                w_c = np.linalg.solve(A, rhs)
            except np.linalg.LinAlgError:
                w_c = np.linalg.pinv(A) @ rhs

            self.chem_weights[chem] = w_c
            self.chem_intercepts[chem] = float(y_mean - X_mean @ w_c)

        self.is_fitted = True
        return self

    def predict(self, X: np.ndarray, chemistries: List[str]) -> np.ndarray:
        if not self.is_fitted:
            raise RuntimeError("Model must be fitted before predict.")
        preds = np.zeros(len(X))
        for i, chem in enumerate(chemistries):
            if chem in self.chem_weights:
                preds[i] = float(X[i] @ self.chem_weights[chem] + self.chem_intercepts[chem])
            else:
                preds[i] = float(X[i] @ self.global_weights + self.global_intercept)
        return preds


