@dataclass
class DomainValidityAssessment:
    """
    Outcome of the Chemistry / Domain Validity Layer evaluation.
    Determines whether a specimen lies within the scientifically validated domain.
    """
    is_domain_supported: bool
    epistemic_state: EpistemicDomainState
    chemistry_confidence: float
    domain_shift_detected: bool
    overconfidence_risk: bool
    recommended_action: str             # "PROCEED_TO_ESTIMATION", "DEFER", "HOLD_FOR_DIAGNOSTICS"
    flags: List[str] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "is_domain_supported": self.is_domain_supported,
            "epistemic_state": self.epistemic_state.value,
            "chemistry_confidence": self.chemistry_confidence,
            "domain_shift_detected": self.domain_shift_detected,
            "overconfidence_risk": self.overconfidence_risk,
            "recommended_action": self.recommended_action,
            "flags": self.flags
        }


class DomainValidityLayer:
    """
    Chemistry / Domain Validity Layer.
    Inserted between Feature Extraction and SOH Estimation in the canonical pipeline:

        RAW DATA
           ↓
        DATA QUALITY
           ↓
        MEASUREMENT VALIDITY
           ↓
        FEATURE EXTRACTION
           ↓
        CHEMISTRY / DOMAIN VALIDITY  <--- THIS LAYER
           ↓
        SOH ESTIMATION
           ↓
        RUL ESTIMATION
           ↓
        UNCERTAINTY
           ↓
        PROGNOSTIC IDENTIFIABILITY
           ↓
        RISK / EVIDENCE
           ↓
        QUALIFICATION DECISION

    RULE: A prediction from an unsupported or shifted domain must NOT
    automatically become a confident qualification decision.

    PHASE 6.1 AUDIT STATUS:
    - Component Status: PROTOTYPE / PROVISIONAL DOMAIN-GATING COMPONENT.
    - min_chemistry_confidence (0.90): PROVISIONAL ENGINEERING THRESHOLD.
      The threshold has not been prospectively calibrated against a sufficient physical domain-validation cohort.
    - AUTHORITY LIMIT: DomainValidityLayer is an informational domain filter and has ZERO authority
      over physical HardSafetyBarrier, HERMES analog hardware comparators, or ActuationPolicy.
    """
    def __init__(
        self,
        supported_chemistries: Optional[Set[str]] = None,
        min_chemistry_confidence: float = 0.90,  # PROVISIONAL ENGINEERING THRESHOLD
        temp_bounds_c: Tuple[float, float] = (10.0, 45.0),
        v_mean_lfp_bounds_v: Tuple[float, float] = (2.80, 3.45),
        v_mean_nmc_bounds_v: Tuple[float, float] = (3.20, 4.15)
    ):
        self.supported_chemistries = supported_chemistries or {"LFP", "NMC"}
        self.min_chem_conf = min_chemistry_confidence  # PROVISIONAL ENGINEERING THRESHOLD
        self.temp_bounds = temp_bounds_c
        self.v_lfp_bounds = v_mean_lfp_bounds_v
        self.v_nmc_bounds = v_mean_nmc_bounds_v

    def evaluate(
        self,
        chemistry: str,
        chemistry_confidence: float,
        chemistry_provenance: ChemistryProvenance,
        features: Dict[str, float]
    ) -> DomainValidityAssessment:
        flags = []
        is_supported = True
        epistemic = EpistemicDomainState.SUPPORTED_HEALTHY
        action = "PROCEED_TO_ESTIMATION"
        overconfidence_risk = False
        domain_shift = False

        # 1. Chemistry Support Check
        if chemistry == "UNKNOWN" or chemistry_provenance == ChemistryProvenance.UNKNOWN:
            flags.append("UNMODELED_OR_UNKNOWN_CHEMISTRY")
            is_supported = False
            epistemic = EpistemicDomainState.DISTRIBUTION_SHIFTED
            action = "DEFER"
            domain_shift = True
        elif chemistry not in self.supported_chemistries:
            flags.append(f"UNSUPPORTED_CHEMISTRY_{chemistry}")
            is_supported = False
            epistemic = EpistemicDomainState.DISTRIBUTION_SHIFTED
            action = "DEFER"
            domain_shift = True
        elif chemistry_confidence < self.min_chem_conf:
            flags.append("AMBIGUOUS_CHEMISTRY_IDENTITY")
            is_supported = False
            epistemic = EpistemicDomainState.UNCERTAIN
            action = "HOLD_FOR_DIAGNOSTICS"
            domain_shift = True

        # 2. Temperature Boundary Check
        temp_c = features.get("T_MEAN", 25.0)
        if temp_c is not None:
            if temp_c < self.temp_bounds[0] or temp_c > self.temp_bounds[1]:
                flags.append(f"TEMPERATURE_OUT_OF_DOMAIN_{temp_c:.1f}C")
                is_supported = False
                epistemic = EpistemicDomainState.DISTRIBUTION_SHIFTED
                action = "DEFER"
                domain_shift = True

        # 3. Voltage Plateau Consistency Check
        v_mean = features.get("V_MEAN")
        if v_mean is not None:
            if chemistry == "LFP" and (v_mean < self.v_lfp_bounds[0] or v_mean > self.v_lfp_bounds[1]):
                flags.append(f"LFP_VOLTAGE_PLATEAU_MISMATCH_{v_mean:.3f}V")
                domain_shift = True
                epistemic = EpistemicDomainState.DISTRIBUTION_SHIFTED
                action = "DEFER"
                is_supported = False
            elif chemistry == "NMC" and (v_mean < self.v_nmc_bounds[0] or v_mean > self.v_nmc_bounds[1]):
                flags.append(f"NMC_VOLTAGE_PLATEAU_MISMATCH_{v_mean:.3f}V")
                domain_shift = True
                epistemic = EpistemicDomainState.DISTRIBUTION_SHIFTED
                action = "DEFER"
                is_supported = False

        # 4. Severe Impedance / Degradation Check
        delta_v_total = features.get("DELTA_V_TOTAL")
        if delta_v_total is not None and delta_v_total > 0.50:
            flags.append("SEVERE_TERMINAL_POLARIZATION_HAZARD")
            epistemic = EpistemicDomainState.KNOWN_DEGRADED
            action = "DEFER"

        return DomainValidityAssessment(
            is_domain_supported=is_supported,
            epistemic_state=epistemic,
            chemistry_confidence=chemistry_confidence,
            domain_shift_detected=domain_shift,
            overconfidence_risk=overconfidence_risk,
            recommended_action=action,
            flags=flags
        )
